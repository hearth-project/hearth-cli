// On an account several people share, everyone's lines end up in the same
// ~/.bashrc / ~/.zshrc, and a colleague's `export CODEX_HOME=...` decides
// which Codex config every session uses (and so whether it goes through
// this person's gateway). Sessions of this person's own sshd carry
// HEARTH_USER (SetEnv); a managed block kept at the very end of the rc
// files sets this person's agent homes again for those sessions only.
// Everyone else's sessions are left as they are.

func identityScript(home string) string { return filepath.Join(shellDir(home), "identity.sh") }

// replacedHomesPath lists agent homes an earlier identity block exported
// (what processes started before a switch may still use).
func replacedHomesPath(home string) string {
	return filepath.Join(shellDir(home), "identity-replaced.json")
}

// ReplacedAgentHomes returns, per variable (CODEX_HOME, ...), the dirs
// earlier identity blocks exported and the current one no longer does.
func ReplacedAgentHomes(home string) map[string][]string {
	out := map[string][]string{}
	loadJSON(replacedHomesPath(home), &out)
	return out
}

var exportRE = regexp.MustCompile(`(?m)^\s*export ([A-Z_]+)='((?:[^']|'"'"')*)'$`)

// noteReplacedHomes records the agent homes of the block oldBody that the
// block newBody changes.
func noteReplacedHomes(home, oldBody, newBody string) error {
	exports := func(b string) map[string]string {
		m := map[string]string{}
		for _, x := range exportRE.FindAllStringSubmatch(b, -1) {
			m[x[1]] = strings.ReplaceAll(x[2], `'"'"'`, "'")
		}
		return m
	}
	was, now := exports(oldBody), exports(newBody)
	rep := ReplacedAgentHomes(home)
	changed := false
	for _, v := range agentHomeEnv {
		old := was[v]
		if old == "" || old == now[v] {
			continue
		}
		list := []string{old}
		for _, p := range rep[v] {
			if p != old && p != now[v] && len(list) < 8 {
				list = append(list, p)
			}
		}
		rep[v], changed = list, true
	}
	if !changed {
		return nil
	}
	b, err := jsonIndent(rep)
	if err != nil {
		return err
	}
	return writeFileAtomic(replacedHomesPath(home), b, 0o600)
}

// agentHomeExports are the agent config dirs this person uses: the ones
// configured (hearth agents home) and the defaults of the enabled agents.
func agentHomeExports(home string) map[string]string {
	h, _ := os.UserHomeDir()
	defaults := map[string]string{"codex": filepath.Join(h, ".codex"), "claude": filepath.Join(h, ".claude")}
	homes := AgentHomes(home)
	out := map[string]string{}
	for _, a := range EnabledAgents(home) {
		v, ok := agentHomeEnv[a]
		if !ok {
			continue
		}
		dir := homes[a]
		if dir == "" {
			dir = defaults[a]
		}
		if dir == "" {
			continue
		}
		if ws := WorkspaceOf(home); ws != "" {
			dir = strings.ReplaceAll(dir, "${WORKSPACE}", ws)
		}
		out[v] = paths.Expand(dir)
	}
	return out
}

func shq(s string) string { return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'" }

// identityBody is the script the block sources.
func identityBody(home, email string) string {
	var b strings.Builder
	b.WriteString("# Generated by hearth: on this shared account, sessions of " + email + "'s own sshd\n")
	b.WriteString("# (HEARTH_USER) use their agent homes, whatever lines before this exported.\n")
	fmt.Fprintf(&b, "if [ \"${HEARTH_USER:-}\" = %s ]; then\n", shq(email))
	fmt.Fprintf(&b, "  export HEARTH_HOME=%s\n", shq(home))
	if ws := WorkspaceOf(home); ws != "" {
		fmt.Fprintf(&b, "  export HEARTH_WORKSPACE=%s\n", shq(ws))
	}
	ex := agentHomeExports(home)
	keys := make([]string, 0, len(ex))
	for k := range ex {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "  export %s=%s\n", k, shq(ex[k]))
	}
	b.WriteString("fi\n")
	return b.String()
}

// EnsureIdentityRC keeps the block at the end of the rc files on a shared
// account (a workspace); elsewhere it removes it. The daemon runs it each
// loop, so lines appended after it later (another person's installer) do
// not win. Returns the rc files it changed.
func EnsureIdentityRC(home, email string) ([]string, error) {
	h, _ := os.UserHomeDir()
	rcs := []string{filepath.Join(h, ".bashrc")}
	if _, err := os.Stat(filepath.Join(h, ".zshrc")); err == nil {
		rcs = append(rcs, filepath.Join(h, ".zshrc"))
	}
	script := identityScript(home)
	var changed []string
	if WorkspaceOf(home) == "" || email == "" {
		for _, rc := range rcs {
			if c, err := recipe.UninstallRC(rc, script); err != nil {
				return changed, err
			} else if c {
				changed = append(changed, rc)
			}
		}
		_ = os.Remove(script)
		return changed, nil
	}
	if err := os.MkdirAll(filepath.Dir(script), 0o700); err != nil {
		return nil, err
	}
	body := identityBody(home, email)
	if cur, _ := os.ReadFile(script); string(cur) != body {
		if err := noteReplacedHomes(home, string(cur), body); err != nil {
			return nil, err
		}
		if err := writeFileAtomic(script, []byte(body), 0o600); err != nil {
			return nil, err
		}
	}
	for _, rc := range rcs {
		c, err := recipe.InstallRC(rc, script) // appended last; moved back to the end if lines follow it
		if err != nil {
			return changed, err
		}
		if c {
			changed = append(changed, rc)
		}
	}
	return changed, nil
}
