package recipe

import (
	"bytes"
	"fmt"
	"github.com/hearth-project/hearth-cli/internal/paths"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type scopedEnv struct {
	recipe string
	step   Step
}

// One managed block per activation script, so several people sharing an
// account (each with their own workspace) do not replace each other's hook.
func rcBegin(script string) string {
	return "# >>> hearth env " + script + " (managed; remove with `hearth env uninstall`) >>>"
}
func rcEnd(script string) string { return "# <<< hearth env " + script + " <<<" }

// DefaultRCFile is the interactive shell's rc file: ~/.zshrc when the login
// shell is zsh (the macOS default), ~/.bashrc otherwise.
func DefaultRCFile() string {
	if filepath.Base(os.Getenv("SHELL")) == "zsh" {
		return ExpandHome("~/.zshrc")
	}
	return ExpandHome("~/.bashrc")
}

// EnvScript is the generated activation script.
func EnvScript(stateDir string) string { return filepath.Join(stateDir, "env", "activate.sh") }

// shQuote single-quotes s for POSIX sh.
func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'" }

// expandTilde replaces "~/" at the start of a word with the home directory,
// so values can be single-quoted safely.
func expandTilde(v string) string { return paths.ExpandWords(v) }

func sortedKeys(m map[string]string) []string {
	k := make([]string, 0, len(m))
	for x := range m {
		k = append(k, x)
	}
	sort.Strings(k)
	return k
}

// renderEnv builds the activation script. Unscoped steps apply to every
// shell; scoped ones only once the shell enters one of their directories
// (design doc 14.3: shared root accounts).
func renderEnv(steps []scopedEnv) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by hearth from library recipes. Do not edit.\n")
	body := func(s Step, indent string) {
		for _, k := range sortedKeys(s.Set) {
			fmt.Fprintf(&b, "%sexport %s=%s\n", indent, k, shQuote(expandTilde(s.Set[k])))
		}
		for _, k := range sortedKeys(s.Alias) {
			fmt.Fprintf(&b, "%salias %s=%s\n", indent, k, shQuote(expandTilde(s.Alias[k])))
		}
	}
	var scoped []scopedEnv
	for _, e := range steps {
		if len(e.step.Scope) == 0 {
			fmt.Fprintf(&b, "# recipe %s\n", e.recipe)
			body(e.step, "")
		} else {
			scoped = append(scoped, e)
		}
	}
	if len(scoped) > 0 {
		b.WriteString("_hearth_env() {\n")
		for i, e := range scoped {
			var pats []string
			for _, d := range e.step.Scope {
				d = strings.TrimRight(ExpandHome(d), "/")
				pats = append(pats, shQuote(d), shQuote(d)+"/*")
			}
			flag := fmt.Sprintf("_HEARTH_ENV_%d", i)
			fmt.Fprintf(&b, "  # recipe %s\n  case \"$PWD\" in\n    %s)\n      if [ -z \"${%s:-}\" ]; then\n", e.recipe, strings.Join(pats, "|"), flag)
			body(e.step, "        ")
			fmt.Fprintf(&b, "        export %s=1\n      fi ;;\n  esac\n", flag)
		}
		// Re-check on every prompt: precmd in zsh (macOS default), PROMPT_COMMAND in bash.
		b.WriteString("}\nif [ -n \"${ZSH_VERSION:-}\" ]; then\n  autoload -Uz add-zsh-hook && add-zsh-hook precmd _hearth_env\nelse\n" +
			"  case \";${PROMPT_COMMAND:-};\" in *\";_hearth_env;\"*) ;; *) PROMPT_COMMAND=\"_hearth_env${PROMPT_COMMAND:+;$PROMPT_COMMAND}\" ;; esac\nfi\n_hearth_env\n")
	}
	return b.Bytes()
}

func (r *runner) env(steps []scopedEnv) (string, string) {
	script := renderEnv(steps)
	path := EnvScript(r.opt.StateDir)
	cur, _ := os.ReadFile(path)
	rc := r.opt.RCFile
	if rc == "" {
		rc = DefaultRCFile()
	}
	unscoped := 0
	for _, e := range steps {
		if len(e.step.Scope) == 0 {
			unscoped++
		}
	}
	note := ""
	if unscoped > 0 {
		note = fmt.Sprintf(" (%d unscoped step(s) affect every shell of this account)", unscoped)
	}
	if r.opt.DryRun {
		return "would-run", "write " + path + " and source it from " + rc + note
	}
	changedRC, err := InstallRC(rc, path)
	if err != nil {
		return "failed", err.Error()
	}
	if bytes.Equal(cur, script) && !changedRC {
		return "ok", path + note
	}
	if err := writeAtomic(path, script, 0o644); err != nil {
		return "failed", err.Error()
	}
	return "applied", fmt.Sprintf("%s, sourced from %s; open a new shell or `source %s`%s", path, rc, path, note)
}

func rcBlock(script string) string {
	return rcBegin(script) + "\n[ -f " + shQuote(script) + " ] && . " + shQuote(script) + "\n" + rcEnd(script) + "\n"
}

// InstallRC adds (or refreshes) the managed block in rc. It only ever
// touches the lines between the markers.
func InstallRC(rc, script string) (bool, error) {
	old, err := os.ReadFile(rc)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	stripped := stripBlock(string(old), script)
	next := stripped
	if next != "" && !strings.HasSuffix(next, "\n") {
		next += "\n"
	}
	next += rcBlock(script)
	if next == string(old) {
		return false, nil
	}
	mode := os.FileMode(0o644)
	if fi, err := os.Stat(rc); err == nil {
		mode = fi.Mode().Perm()
	}
	return true, writeAtomic(rc, []byte(next), mode)
}

// UninstallRC removes the managed block of script.
func UninstallRC(rc, script string) (bool, error) {
	old, err := os.ReadFile(rc)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	next := stripBlock(string(old), script)
	if next == string(old) {
		return false, nil
	}
	fi, _ := os.Stat(rc)
	return true, writeAtomic(rc, []byte(next), fi.Mode().Perm())
}

func stripBlock(s, script string) string {
	begin, endMark := rcBegin(script), rcEnd(script)
	for {
		i := strings.Index(s, begin)
		if i < 0 {
			return s
		}
		j := strings.Index(s[i:], endMark)
		if j < 0 {
			return s
		}
		end := i + j + len(endMark)
		if end < len(s) && s[end] == '\n' {
			end++
		}
		s = s[:i] + s[end:]
	}
}
